"""Secure credential management for WHO API Client."""

import os

import keyring
from dotenv import load_dotenv

# Service name for keyring storage
SERVICE_NAME = "who-api-client"
EMAIL_KEY = "email"
PASSWORD_KEY = "password"


class CredentialManager:
    """Manages credential storage and retrieval with multiple backends."""

    def __init__(self):
        """Initialize credential manager and load environment variables."""
        load_dotenv()

    def get_credentials(self) -> tuple[str | None, str | None]:
        """
        Get credentials from available sources in priority order.

        Returns:
            Tuple of (email, password) or (None, None) if not found

        Priority order:
        1. Environment variables (for CI/CD)
        2. System keyring (secure local storage)
        3. .env file (backward compatibility)
        """
        # 1. Check environment variables first (highest priority for CI/CD)
        email = os.getenv("WHO_EMAIL")
        password = os.getenv("WHO_PASSWORD")

        if email and password:
            return email, password

        # 2. Check system keyring
        try:
            keyring_email = keyring.get_password(SERVICE_NAME, EMAIL_KEY)
            keyring_password = keyring.get_password(SERVICE_NAME, PASSWORD_KEY)

            if keyring_email and keyring_password:
                return keyring_email, keyring_password
        except Exception:
            # Keyring might not be available on all systems
            pass

        # 3. Already loaded from .env via load_dotenv() in __init__
        # Return None, None if no credentials found anywhere
        return None, None

    def save_credentials(
        self, email: str, password: str, use_keyring: bool = True
    ) -> None:
        """
        Save credentials to storage.

        Args:
            email: User email
            password: User password
            use_keyring: If True, save to keyring. If False, save to .env file
        """
        if use_keyring:
            try:
                keyring.set_password(SERVICE_NAME, EMAIL_KEY, email)
                keyring.set_password(SERVICE_NAME, PASSWORD_KEY, password)
            except Exception as e:
                raise RuntimeError(f"Failed to save credentials to keyring: {e}") from e
        else:
            # Save to .env file
            env_path = os.path.join(os.getcwd(), ".env")

            # Read existing .env content if it exists
            existing_content = {}
            if os.path.exists(env_path):
                with open(env_path) as f:
                    for line in f:
                        line = line.strip()
                        if line and not line.startswith("#") and "=" in line:
                            key, value = line.split("=", 1)
                            existing_content[key.strip()] = value.strip()

            # Update with new credentials
            existing_content["WHO_EMAIL"] = email
            existing_content["WHO_PASSWORD"] = password

            # Write back to file
            with open(env_path, "w") as f:
                f.write("# WHO API Credentials\n")
                f.write("# Auto-generated by who-api-client login\n\n")
                for key, value in existing_content.items():
                    f.write(f"{key}={value}\n")

    def clear_credentials(self) -> None:
        """Clear stored credentials from keyring."""
        errors = []

        # First, try to overwrite with empty values (sometimes helps with keychain issues)
        try:
            if keyring.get_password(SERVICE_NAME, EMAIL_KEY):
                keyring.set_password(SERVICE_NAME, EMAIL_KEY, "")
        except Exception:
            pass

        try:
            if keyring.get_password(SERVICE_NAME, PASSWORD_KEY):
                keyring.set_password(SERVICE_NAME, PASSWORD_KEY, "")
        except Exception:
            pass

        # Now try to delete email
        try:
            keyring.delete_password(SERVICE_NAME, EMAIL_KEY)
        except keyring.errors.PasswordDeleteError:
            # This is fine - password doesn't exist
            pass
        except Exception as e:
            # If it's a "not found" type error, that's fine too
            if "not found" not in str(e).lower():
                errors.append(f"Failed to delete email: {e}")

        # Try to delete password
        try:
            keyring.delete_password(SERVICE_NAME, PASSWORD_KEY)
        except keyring.errors.PasswordDeleteError:
            # This is fine - password doesn't exist
            pass
        except Exception as e:
            # If it's a "not found" type error, that's fine too
            if "not found" not in str(e).lower():
                errors.append(f"Failed to delete password: {e}")

        # If there were non-expected errors, raise them
        if errors:
            raise RuntimeError("; ".join(errors))

    def has_credentials(self) -> bool:
        """Check if any credentials are available."""
        email, password = self.get_credentials()
        return bool(email and password)

    def get_credential_source(self) -> str | None:
        """
        Determine where credentials are coming from.

        Returns:
            String describing the credential source or None if no credentials
        """
        # Check environment variables
        if os.getenv("WHO_EMAIL") and os.getenv("WHO_PASSWORD"):
            return "environment variables"

        # Check keyring
        try:
            if keyring.get_password(SERVICE_NAME, EMAIL_KEY) and keyring.get_password(
                SERVICE_NAME, PASSWORD_KEY
            ):
                return "system keyring"
        except Exception:
            pass

        # Check if loaded from .env
        email, password = self.get_credentials()
        if email and password:
            return ".env file"

        return None

    def debug_keyring_info(self) -> dict[str, str | None]:
        """Get debug information about keyring storage."""
        info = {
            "backend": str(keyring.get_keyring()),
            "service_name": SERVICE_NAME,
            "email_key": EMAIL_KEY,
            "password_key": PASSWORD_KEY,
        }

        # Check if we can read from keyring
        try:
            email = keyring.get_password(SERVICE_NAME, EMAIL_KEY)
            info["email_stored"] = "Yes" if email else "No"
        except Exception as e:
            info["email_stored"] = f"Error: {e}"

        try:
            password = keyring.get_password(SERVICE_NAME, PASSWORD_KEY)
            info["password_stored"] = "Yes" if password else "No"
        except Exception as e:
            info["password_stored"] = f"Error: {e}"

        return info
